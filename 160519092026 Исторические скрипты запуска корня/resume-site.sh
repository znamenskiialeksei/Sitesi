#!/bin/bash

# Остановка выполнения скрипта при возникновении любых критических ошибок
set -e

echo "Запуск скрипта восстановления работы сайта из родительской директории..."

# Проверяем, что папка проекта на месте, чтобы избежать выполнения команд в неправильной директории
if [ ! -d "villa-turaman-platform" ]; then
    echo "Критическая ошибка: Папка villa-turaman-platform не найдена в текущем расположении!"
    exit 1
fi

# Переходим в директорию целевого репозитория для выполнения команд Git
echo "Переход в репозиторий villa-turaman-platform..."
cd villa-turaman-platform

# Удаляем файлы режима технического обслуживания из файловой системы и сразу из индекса Git
echo "Удаление файла заглушки (maintenance.html) и временной конфигурации маршрутизации (vercel.json)..."
git rm -f maintenance.html vercel.json

# Фиксируем изменения (удаление файлов) в истории Git с понятным сообщением
echo "Создание коммита с отменой режима обслуживания..."
git commit -m "Fix: Отключение режима обслуживания и восстановление стандартной маршрутизации"

# Отправляем коммит на удаленный сервер GitHub для автоматического запуска новой сборки Vercel
echo "Отправка изменений в GitHub..."
git push origin main

echo "---------------------------------------------------"
echo "УСПЕШНО! Режим обслуживания деактивирован."
echo "Скрипт resume-site.sh отработал корректно и восстановил доступ к проекту."
